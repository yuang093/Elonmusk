print()
print("=== LAYER 2 -- the BANNER (the VISIBLE layer) ===")
# ⭐⭐⭐ THE TWO LAYERS HAVE *DIFFERENT* FORMATS, AND THE PATTERNS MUST
# MATCH THE LAYER EACH ONE READS (the 1223 class):
#   * the SOURCE layer carries the markup form  ->  `已連續 <strong>372</strong> 次回傳`
#   * the VISIBLE layer carries the plain form   ->  `已連續 372 次回傳`
# ⇒ ⇒ ⇒ A PATTERN THAT MATCHES ONE FORM IS SILENTLY ZERO ON THE OTHER ⇒ ⇒ ⇒
# ⇒ ⇒ ⇒ AND *BOTH* LAYERS MUST BE READ, AND THEY MUST AGREE.
_SRC_BANNER_RE = re.compile(
    r"已連續\s*<strong>(\d+)</strong>\s*次回傳 0 則推文")
_VIS_BANNER_RE = re.compile(r"已連續 (\d+) 次回傳 0 則推文")

# ⭐ THE VISIBLE LAYER IS READ WITH lxml -- NOT `html.parser` (the 1185
# class: `html.parser` does NOT implement HTML5's "head-side non-whitespace
# opens an implicit body" rule, so it can report a healthy page as clean).
try:
    from lxml import html as _lhtml
except ImportError:
    _lhtml = None
if _lhtml is not None:
    _tree = _lhtml.fromstring(served_html)
    for _bad in _tree.xpath("//script|//style"):
        _bad.getparent().remove(_bad)
    visible = _tree.text_content()
    _engine = "lxml"
else:
    # ⭐ THE FALLBACK MUST SAY SO -- an instrument that silently changes
    # engine is an instrument whose result cannot be compared.
    import html.parser as _hp

    class _T(_hp.HTMLParser):
        def __init__(self):
            super().__init__()
            self.buf = []
            self._skip = 0

        def handle_starttag(self, tag, attrs):
            if tag in ("script", "style"):
                self._skip += 1

        def handle_endtag(self, tag):
            if tag in ("script", "style") and self._skip:
                self._skip -= 1

        def handle_data(self, data):
            if not self._skip:
                self.buf.append(data)

    _t = _T()
    _t.feed(served_html)
    visible = "".join(_t.buf)
    _engine = "html.parser (FALLBACK -- lxml unavailable)"
print(f"[lb] the visible-text engine: {_engine}")

