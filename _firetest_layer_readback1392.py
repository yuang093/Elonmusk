def _run_readback(repo, served_stamp, served_html, served_json):
    """Run the read-back against a POISONED repo+served set."""
    with tempfile.TemporaryDirectory() as _td:
        _d = pathlib.Path(_td)
        # the read-back reads HEAD:<file> from the repo and /tmp/_1392_served.*
        # from FIXED paths -- so the poisoned copies are staged there.
        _stage_stamp = pathlib.Path("/tmp/_1392_served_stamp.txt")
        _stage_html = pathlib.Path("/tmp/_1392_served.html")
        _stage_json = pathlib.Path("/tmp/_1392_served.json")
        _backup = {}
        for _p in (_stage_stamp, _stage_html, _stage_json):
            _backup[_p] = _p.read_bytes() if _p.exists() else None
        try:
            _stage_stamp.write_text(served_stamp, encoding="utf-8")
            _stage_html.write_text(served_html, encoding="utf-8")
            _stage_json.write_text(served_json, encoding="utf-8")
            _r = subprocess.run([sys.executable, str(READBACK)],
                                cwd=str(repo), capture_output=True,
                                text=True, timeout=300)
            return _r
        finally:
            for _p, _b in _backup.items():
                if _b is None:
                    if _p.exists():
                        _p.unlink()
                else:
                    _p.write_bytes(_b)


